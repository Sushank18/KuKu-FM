# 3. DATA NORMALIZATION & PROMO SCORING HEURISTIC
# ==============================================================================
def normalize_and_score_promos(df: pd.DataFrame) -> pd.DataFrame:
    """
    Normalizes column naming variations across pipeline iterations and applies
    a proprietary Promo Virality Ranking Score (0 to 100).
    """
    data = df.copy()

    # Map column aliases for flexibility
    col_mapping = {
        "Start_Timecode": "Start_Time",
        "Raw_Start_Time": "Start_Time",
        "End_Timecode": "End_Time",
        "Raw_End_Time": "End_Time",
        "Hook": "Hook_Description",
        "Cliffhanger": "Cliffhanger_Description"
    }
    for old_col, new_col in col_mapping.items():
        if old_col in data.columns and new_col not in data.columns:
            data[new_col] = data[old_col]

    # Ensure required columns exist with sensible defaults
    required_cols = ["Episode", "Start_Time", "End_Time", "Duration_Sec", "Hook_Description", "Cliffhanger_Description", "Justification"]
    for col in required_cols:
        if col not in data.columns:
            data[col] = "N/A"

    # Ensure Duration_Sec is numeric
    data["Duration_Sec"] = pd.to_numeric(data["Duration_Sec"], errors="coerce").fillna(30.0)

    # -------------------------------------------------------------
    # Promo Virality Scoring Algorithm (0 to 100)
    # -------------------------------------------------------------
    # Optimal vertical ad duration sweet-spot: 30 to 45 seconds
    # Formula rewards clips closer to 38s and penalizes extremes
    duration_scores = 100 - (data["Duration_Sec"] - 38.0).abs() * 2.2
    duration_scores = duration_scores.clip(lower=40, upper=100)

    # Keyword bonus for high emotional intensity
    high_impact_keywords = ["betrayal", "altar", "slap", "punch", "seal", "duke", "forgery", "secret", "rejection"]
    keyword_bonus = data.apply(
        lambda r: sum(
            4 for kw in high_impact_keywords 
            if kw in str(r["Hook_Description"]).lower() or kw in str(r["Cliffhanger_Description"]).lower()
        ),
        axis=1
    )

    data["Virality_Score"] = (duration_scores * 0.70 + keyword_bonus * 0.30).round(1).clip(upper=99.8)

    # Sort descending by Virality Score
    data = data.sort_values(by="Virality_Score", ascending=False).reset_index(drop=True)
    return data


